def P(text: str, mark: str = "") -> tuple:
    return ("p", text, mark)


def H(text: str, mark: str = "") -> tuple:
    return ("h", text, mark)


def NOTE(text: str, mark: str = "") -> tuple:
    return ("note", text, mark)


def STEPS(*items, mark: str = "") -> tuple:
    """What is done one after another.  An item — its text, or (text, mark)."""
    return ("steps", items, mark)


def LIST(*items, mark: str = "") -> tuple:
    return ("list", items, mark)


def KEYS(*rows, mark: str = "") -> tuple:
    """Rows (the keys, what they do)."""
    return ("keys", rows, mark)


