TITLES = {section_id: title for section_id, title, _pages, _blocks in SECTIONS}
_MARK = re.compile(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]|<<([a-z]+)>>|\{\{([^}]+)\}\}|`([^`]+)`")
_TO = re.compile(r'<a class="hp-to" href="#' + ANCHOR + r'([a-z]+)">(«[^<]*»)</a>')


def _item(item) -> tuple:
    """An item of a list as (text, mark)."""
    return item if isinstance(item, tuple) else (item, "")


def texts() -> list:
    """[(section id, a text of it)] — every line of every section, whatever the mode (the check's list)."""
    out = []
    for section_id, _title, _pages, blocks in SECTIONS:
        for kind, value, _mark in blocks:
            if isinstance(value, str):
                out.append((section_id, value))
            elif kind == "keys":
                out += [(section_id, cell) for row in value for cell in row]
            else:
                out += [(section_id, _item(item)[0]) for item in value]
    return out


def names() -> list:
    """[(section id, the name, its address or "")] — everything the text names in the program (the check's list)."""
    return [(section_id, m.group(1), m.group(2) or "") for section_id, text in texts()
            for m in _MARK.finditer(text) if m.group(1)]


def _inline(text: str) -> str:
    """A line of the text as HTML: the names of the program's things, its links, the keys, what is typed."""
    out, at = [], 0
    for m in _MARK.finditer(text):
        out.append(esc(text[at:m.start()]))
        name, href, section, key, typed = m.groups()
        if section is not None:
            out.append(f'<a class="hp-to" href="#{ANCHOR}{esc(section)}">«{esc(TITLES.get(section, section))}»</a>')
        elif key is not None:
            out.append(f"<kbd>{esc(key)}</kbd>")
        elif typed is not None:
            out.append(f"<code>{esc(typed)}</code>")
        elif href:
            out.append(f'<a class="hp-name" href="{esc(href)}">{esc(name)}</a>')
        else:
            out.append(f'<b class="hp-name">{esc(name)}</b>')
        at = m.end()
    out.append(esc(text[at:]))
    return "".join(out)


def _shown(mark: str, mode: str) -> bool:
    if mark == BEYOND:
        return mode != "sfw"
    if mark == DUBS:
        from core import video_dubs
        return bool(getattr(video_dubs, "AVAILABLE", True))
    return True


def _block(block: tuple, mode: str) -> str:
    kind, value, mark = block
    if not _shown(mark, mode):
        return ""
    if kind == "p":
        return f"<p>{_inline(value)}</p>"
    if kind == "h":
        return f"<h3>{_inline(value)}</h3>"
    if kind == "note":
        return f'<p class="hp-note">{_inline(value)}</p>'
    if kind in ("steps", "list"):
        lines = "".join(f"<li>{_inline(text)}</li>" for text, own in map(_item, value) if _shown(own, mode))
        tag = "ol" if kind == "steps" else "ul"
        return f'<{tag} class="hp-{kind}">{lines}</{tag}>' if lines else ""
    if kind == "keys":
        rows = "".join(f'<tr><th scope="row">{_inline(keys)}</th><td>{_inline(what)}</td></tr>'
                       for keys, what in value)
        return f'<table class="hp-keys"><tbody>{rows}</tbody></table>'
    return ""


def shown_ids(mode: str) -> tuple:
    """The ids of the sections this mode shows: all but those of the pages it hides."""
    from webui import content_mode
    return tuple(section_id for section_id, _title, pages, _blocks in SECTIONS
                 if not pages or any(content_mode.page_shown(page, mode) for page in pages))


def sections(mode: str) -> list:
    """[(id, title, html)] of the sections this mode shows."""
    here = set(shown_ids(mode))
    shown = [(section_id, title, blocks) for section_id, title, _pages, blocks in SECTIONS if section_id in here]
    out = []
    for section_id, title, blocks in shown:
        parts = [part for part in (_block(block, mode) for block in blocks) if part]
        # a heading whose lines this mode leaves out goes with them
        kept = [part for i, part in enumerate(parts)
                if not (part.startswith("<h3>") and (i + 1 == len(parts) or parts[i + 1].startswith("<h3>")))]
        # a link to a section this mode does not show — its title alone
        body = _TO.sub(lambda m: m.group(0) if m.group(1) in here else m.group(2), "".join(kept))
        out.append((section_id, title, body))
    return out


def body_html(mode: str) -> str:
    shown = sections(mode)
    contents = "".join(f'<li><a href="#{ANCHOR}{esc(sid)}">{esc(title)}</a></li>' for sid, title, _body in shown)
    parts = "".join(f'<section class="hp-section" id="{ANCHOR}{esc(sid)}" aria-labelledby="{ANCHOR}{esc(sid)}-h">'
                    f'<h2 id="{ANCHOR}{esc(sid)}-h">{esc(title)}</h2>{body}</section>' for sid, title, body in shown)
    return ('<div class="hp" id="help-page">'
            '<header class="hp-head"><h1>Справка</h1>'
            '<p class="hp-lead">Как пользоваться программой — по тому, что вы хотите сделать.</p>'
            '<div class="hp-find"><label for="hp-find">Найти в справке</label>'
            '<input type="search" id="hp-find" placeholder="например: подписка, корзина, озвучка" '
            'autocomplete="off" spellcheck="false"></div>'
            '<p class="hp-none" id="hp-none" role="status" hidden>Таких слов в справке нет.</p></header>'
            f'<div class="hp-cols"><nav class="hp-contents" aria-label="Разделы справки"><ol>{contents}</ol></nav>'
            f'<div class="hp-text">{parts}</div></div></div>')


def register(router) -> None:
    router.add("GET", r"/help", page)


def page(req: Request) -> Response:
    from webui import content_mode
    return Response.html(page_frame("Справка", body_html(content_mode.mode()), active="help", subnav=False))


def address(active: str, kind: str = "", mode: str = "all") -> str:
    """Where the «?» of a page leads: the help, at the section about that page (a section this mode does not show —
    the help's top)."""
    section = SECTION_OF_KIND.get(kind) or SECTION_OF.get(active, "")
    return "/help#" + ANCHOR + section if section in shown_ids(mode) else "/help"
