    def open_random_post(self):
        try:
            import random

            items = []

            if hasattr(self, "gallery_items"):
                items = self.gallery_items
            elif hasattr(self.main, "gallery_page") and hasattr(self.main.gallery_page, "items"):
                items = self.main.gallery_page.items

            if not items:
                return

            current = getattr(self, "current_path", None)

            valid = [x for x in items if str(x) != str(current)]

            if not valid:
                valid = items

            chosen = random.choice(valid)

            if hasattr(self, "load_post"):
                self.load_post(chosen)
            elif hasattr(self.main, "open_post"):
                self.main.open_post(chosen)

        except Exception as e:
            print("RANDOM ERROR:", e)


    def setup_random_viewer_button(self):
        from PyQt5.QtWidgets import QPushButton

        self.viewer_random_btn = QPushButton("🎲")
        self.viewer_random_btn.setFixedSize(42, 42)
        self.viewer_random_btn.clicked.connect(self.open_random_post)

        try:
            self.top_controls_layout.insertWidget(
                self.top_controls_layout.count() - 1,
                self.viewer_random_btn
            )
        except Exception:
            pass

    def open_random_post(self):
        try:
            import random

            items = []

            if hasattr(self.main, "gallery_page"):
                gp = self.main.gallery_page

                if hasattr(gp, "filtered_posts"):
                    items = gp.filtered_posts
                elif hasattr(gp, "posts"):
                    items = gp.posts
                elif hasattr(gp, "items"):
                    items = gp.items

            if not items:
                return

            current = getattr(self, "current_post", None)

            valid = [x for x in items if x != current]

            if not valid:
                valid = items

            post = random.choice(valid)

            if hasattr(self, "open_post"):
                self.open_post(post)
            elif hasattr(self.main, "open_post"):
                self.main.open_post(post)

        except Exception as e:
            print("VIEWER RANDOM ERROR:", e)
